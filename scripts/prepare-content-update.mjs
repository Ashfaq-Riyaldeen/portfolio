const quote = (value) => "'" + String(value).replaceAll("'", "''") + "'";
const jsonColumns = new Set(["profile.quick_facts", "profile.socials", "skill_categories.skills"]);
function literal(value, column, table) {
  if (value == null) return "null";
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  if (Array.isArray(value)) {
    return jsonColumns.has(`${table}.${column}`)
      ? quote(JSON.stringify(value)) + "::jsonb"
      : "array[" + value.map(quote).join(", ") + "]::text[]";
  }
  return quote(value);
}
function snake(record) {
  return Object.fromEntries(Object.entries(record).map(([key, value]) => [key.replace(/[A-Z]/g, (c) => "_" + c.toLowerCase()), value]));
}
function stableId(table, key) {
  const hash = createHash("sha256").update(`portfolio-2026-11:${table}:${key}`).digest("hex");
  return `${hash.slice(0,8)}-${hash.slice(8,12)}-5${hash.slice(13,16)}-a${hash.slice(17,20)}-${hash.slice(20,32)}`;
}
