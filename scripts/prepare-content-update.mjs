const normalizeKey = (value) => String(value).replaceAll(" — ", ": ").toLowerCase();
const equivalent = (a, b) => normalizeKey(a) === normalizeKey(b);
function original(table, key, value) {
  return (before[table] ?? []).find((row) => equivalent(row[key], value) || equivalent(row[key], aliases[value] ?? value));
}
function upsert(table, row, conflict = "id", preserve = []) {
  const columns = Object.keys(row);
  const updates = columns.filter((column) => column !== conflict).map((column) => {
    if (preserve.includes(column)) return `${column} = coalesce(public.${table}.${column}, excluded.${column})`;
    return `${column} = excluded.${column}`;
  });
  return `insert into public.${table} (${columns.join(", ")})\nvalues (${columns.map((column) => literal(row[column], column, table)).join(", ")})\non conflict (${conflict}) do update set ${updates.join(", ")};`;
}
