const inserted = [];
const affected = new Map();
function remember(table, row) {
  if (!row) return;
  if (!affected.has(table)) affected.set(table, new Map());
  affected.get(table).set(row.id ?? row.key, row);
}
function add(table, record, key, sortOrder, preserve = []) {
  const row = snake(record);
  const previous = original(table, key, row[key]);
  const conflict = table === "sections" ? "key" : "id";
  if (conflict === "id") row.id = previous?.id ?? (key === "id" ? row.id : stableId(table, row[key]));
  if (sortOrder != null) row.sort_order = sortOrder;
  if (previous) remember(table, previous);
  else inserted.push({ table, key: conflict, value: row[conflict] });
  forward.push(upsert(table, row, conflict, preserve));
}
