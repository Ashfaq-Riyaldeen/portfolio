/** Icon for a social platform name, falling back to a globe. */
export function SocialIcon({
  platform,
  className,
}: {
  platform: string;
  className?: string;
}) {
  const key = platform.toLowerCase().replace(/[\s-]+/g, "");
  const Icon = Object.prototype.hasOwnProperty.call(icons, key) ? icons[key] : Globe;
  return <Icon className={className} />;
}
